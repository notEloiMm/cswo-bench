"""Resolve aquatic taxon names to iNaturalist taxon IDs and GBIF taxon keys -> configs/aquatic_taxa.yaml.

obligate: true  -> every observation is a water record (fish, aquatic plants, marine mammals, ...).
obligate: false -> kept only if locality/habitat/note mentions a water body (dragonflies, waterbirds, amphibians, ...).
Run: uv run python scripts/resolve_taxa.py
"""
import time

import requests
import yaml

from cswo import CONFIGS

TAXA = {
    # obligate aquatic
    "Actinopterygii": True, "Petromyzontiformes": True, "Bivalvia": True, "Cetacea": True,
    "Nymphaeaceae": True, "Potamogetonaceae": True, "Characeae": True, "Hydrocharitaceae": True,
    "Haloragaceae": True, "Lemnoideae": True, "Gerridae": True, "Dytiscidae": True, "Nepomorpha": True,
    "Gammaridae": True, "Astacidea": True, "Asteroidea": True, "Scyphozoa": True, "Fucales": True,
    "Laminariales": True, "Spongillidae": True, "Ephemeroptera": True, "Plecoptera": True,
    # facultative: need a water-body keyword
    "Odonata": False, "Trichoptera": False, "Pinnipedia": False, "Anatidae": False, "Gaviidae": False,
    "Podicipedidae": False, "Laridae": False, "Ardeidae": False, "Alcedinidae": False, "Rallidae": False,
    "Typhaceae": False, "Hirudinea": False, "Cinclidae": False, "Castor": False, "Lutra": False,
    "Anura": False, "Caudata": False,
}


# GBIF occurrences are now interpreted against the Catalogue of Life XR checklist. Its keys differ from the old
# backbone's integer keys (old order key 495 is a slime-mould order in XR), so GBIF SQL filters on rank *names*.
# Groups whose XR rank has no occurrence column (gigaclass, infraorder, ...) are replaced by constituent taxa.
XR_CHECKLIST = "7ddf754f-d193-4cc9-b351-99906754a03b"
SQL_RANKS = {"PHYLUM", "CLASS", "ORDER", "SUPERFAMILY", "FAMILY", "SUBFAMILY", "GENUS"}
GBIF_ALIASES = {
    "Actinopterygii": ["Teleostei", "Acipenseriformes", "Amiiformes", "Lepisosteiformes"],
    "Nepomorpha": ["Notonectidae", "Corixidae", "Nepidae", "Naucoridae", "Pleidae"],
    "Astacidea": ["Astacidae", "Cambaridae", "Nephropidae"],
    "Hirudinea": ["Hirudinidae", "Erpobdellidae", "Glossiphoniidae", "Haemopidae"],
    "Pinnipedia": ["Phocidae", "Otariidae", "Odobenidae"],
    "Lemnoideae": ["Lemnaceae"],
    "Plecoptera": ["Perlidae", "Perlodidae", "Nemouridae", "Leuctridae", "Capniidae", "Taeniopterygidae",
                   "Chloroperlidae"],
    "Anura": ["Anura|class=Amphibia"],          # "name|rank=parent" disambiguates homonyms
}


def xr_taxa(s: requests.Session, name: str) -> list[dict]:
    """[{rank, name}] usable as `<rank column> IN (...)` in GBIF SQL."""
    out = []
    for alias in GBIF_ALIASES.get(name, [name]):
        n, *hint = alias.split("|")
        r = s.get("https://api.gbif.org/v2/species/match",
                  params={"checklistKey": XR_CHECKLIST, "scientificName": n, **dict(h.split("=") for h in hint)},
                  timeout=30).json()
        u = r.get("usage") or {}
        if r.get("diagnostics", {}).get("matchType") == "EXACT" and u.get("rank") in SQL_RANKS:
            out.append({"rank": u["rank"].lower(), "name": u["canonicalName"]})
        else:
            print(f"  ! {n}: XR rank {u.get('rank')} not filterable; add constituent taxa to GBIF_ALIASES", flush=True)
    return out


def main() -> None:
    out = []
    s = requests.Session()
    for name, obligate in TAXA.items():
        res = s.get("https://api.inaturalist.org/v1/taxa", params={"q": name, "per_page": 10}, timeout=30).json()["results"]
        inat = next((t for t in res if t["name"] == name), None)
        row = {"name": name, "obligate": obligate,
               "inat_id": inat["id"] if inat else None,
               "gbif_xr": xr_taxa(s, name)}
        print(row, flush=True)
        out.append(row)
        time.sleep(1.0)        # iNat asks for <= 1 request/second
    (CONFIGS / "aquatic_taxa.yaml").write_text(
        "# Generated by scripts/resolve_taxa.py; edit TAXA there and rerun.\n" + yaml.safe_dump(out, sort_keys=False),
        encoding="utf-8")


if __name__ == "__main__":
    main()
